import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const context = await browser.newContext({ permissions: ['clipboard-read', 'clipboard-write'], viewport: { width: 1280, height: 900 } });
const page = await context.newPage();
const errors = [];
page.on('pageerror', e => errors.push(e.message));
try {
 await page.goto('http://localhost:5173');
 await page.getByRole('heading', { name: 'Acortador de enlaces', exact: true }).waitFor();
 assert.equal(await page.getByLabel('Estado de caché').count(), 0);
 const original = `https://example.com/parcial?demo=${Date.now()}`;
 await page.getByLabel('Enlace original', { exact: true }).fill(original);
 await page.getByRole('button', { name: 'Acortar →', exact: true }).click();
 const shortLink = page.locator('.result-row > a');
 await shortLink.waitFor();
 const shortUrl = await shortLink.getAttribute('href');
 assert.match(shortUrl, /^http:\/\/localhost:8080\/r\/[A-Za-z0-9]+$/);
 await page.locator('.result').getByRole('button', { name: 'Copiar', exact: true }).click();
 await page.getByText('Enlace copiado', { exact: true }).waitFor();
 assert.equal(await page.evaluate(() => navigator.clipboard.readText()), shortUrl);
 const redirect = await context.request.get(shortUrl, { maxRedirects: 0 });
 assert.equal(redirect.status(), 302);
 assert.equal(redirect.headers().location, original);
 assert.equal((await context.request.get('http://localhost:8080/r/missing-test-code')).status(), 404);
 await page.screenshot({ path: 'create-desktop.png', fullPage: true });
 await page.getByRole('button', { name: 'Ver enlaces' }).click();
 await page.getByLabel('Estado de caché').waitFor();
 await page.getByRole('link', { name: shortUrl, exact: true }).waitFor();
 const first = await (await context.request.get('http://localhost:8080/api/links/cache/status')).json();
 await page.waitForTimeout(2200);
 await page.reload();
 await page.getByLabel('Estado de caché').waitFor();
 const after = await (await context.request.get('http://localhost:8080/api/links/cache/status')).json();
 assert(after.ttlSeconds < first.ttlSeconds, 'Reload must preserve the real remaining TTL');
 await page.screenshot({ path: 'list-desktop.png', fullPage: true });
 await page.waitForTimeout(after.ttlSeconds * 1000 + 1000);
 await page.getByText('Caché expirada', { exact: true }).waitFor();
 assert.equal(await page.getByRole('link', { name: shortUrl, exact: true }).count(), 1);
 assert.equal((await context.request.get(shortUrl, { maxRedirects: 0 })).status(), 302);
 await page.getByRole('button', { name: 'Actualizar listado' }).click();
 await page.getByText(/Última consulta: MongoDB/).waitFor();
 await page.setViewportSize({ width: 390, height: 844 });
 await page.screenshot({ path: 'list-mobile.png', fullPage: true });
 assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
 assert.deepEqual(errors, []);
 console.log('PASS: crear, copiar, 302/404, consultar, recargar sin renovar TTL, expirar sin perder enlaces, reconstruir y vista móvil.');
} finally { await browser.close(); }